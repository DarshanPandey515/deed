import dotenv
import pydantic_ai
from auth import get_service
from gmail_reader import list_inbox
from gmail_composer import create_draft, send_drafts
from triage import agent_summary

dotenv.load_dotenv()
pydantic_ai.BANNER_ENABLED = False


def main():
    context = list_inbox(max_results=3)
    result = agent_summary(context)

    actionable = [r for r in result.results if r.is_actionable]
    
    print("=" * 20)
    print(f"total={len(result.results)} actionable={len(actionable)}")
    
    if not actionable:
        print("No actionable emails to process.")
        return result

    service = get_service()
    
    for r in actionable:
        print(f"[{r.priority}] {r.intent} — {r.suggested_action}  ({r.reason})")
                
        
        draft_body = f"Hi,\n\nRegarding: {r.intent}\n\n[This is a placeholder draft generated by the agent.]\n\nBest,\n[Your Name]"
        
        original_email = next(
            (e for e in context if e["id"] == r.id), None
        )
        
        print(f"original email: {original_email}")
        
        recipient = original_email["From"] if original_email else "unknown@example.com"
        subject = f"Re: {original_email['Subject']}" if original_email else "Re: your email"

        draft = create_draft(
            service=service,
            to=recipient,
            subject=subject,
            body=draft_body,
            thread_id=original_email["id"] if original_email else None,
        )

        print("\n--- DRAFT FOR YOUR REVIEW ---")
        print(f"To: {recipient}")
        print(f"Subject: {subject}")
        print(f"Body:\n{draft_body}")
        print("-----------------------------")

        approval = input("Send this draft? (y/n): ").strip().lower()

        if approval == "y":
            send_drafts(service, draft["id"])
            print("Draft approved and sent.")
        else:
            print("send cancelled. The draft remains in your Gmail drafts folder for later use.")

    return result

if __name__ == "__main__":
    main()
